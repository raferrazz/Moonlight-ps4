"""Bake a licensed font into a compact antialiased master for the native UI.

Bakes Carlito (SIL OFL 1.1, metric-compatible humanist sans - much
closer to the PS4's system letterforms than the old DejaVu bake) rendered at
a 64 px master. The renderer (ui_draw.c) area-average downsamples this
master to any request size, which replaces the old 48 px master + 4-tap
bilinear that left body text frayed at 20-30 px).

Usage: python generate_ui_font.py FONT_DIRECTORY OUTPUT_HEADER
No font library or file I/O is needed on the console.

Output format (consumed by ui_draw.c):
    #define SANS_PT <master point size>
    #define SANS_RH <raster rows per glyph>
    static const struct { unsigned offset; unsigned short width, advance; }
        sans_glyphs[95*2];   /* [0..94] regular, [95..189] bold */
    static const unsigned char sans_pixels[];
"""
from pathlib import Path
import sys

from PIL import Image, ImageDraw, ImageFont

SANS_PT = 64   # master point size
SANS_RH = 88   # raster rows per glyph (ascent + descent + headroom)

root, output = map(Path, sys.argv[1:])
pixels, glyphs = [], []
for filename in ("Carlito-Regular.ttf", "Carlito-Bold.ttf"):
    font = ImageFont.truetype(str(root / filename), SANS_PT)
    for code in range(32, 127):
        advance = round(font.getlength(chr(code)))
        width = advance + 4
        image = Image.new("L", (width, SANS_RH))
        ImageDraw.Draw(image).text((2, 0), chr(code), font=font, fill=255)
        glyphs.append((len(pixels), width, advance))
        pixels.extend(image.tobytes())

lines = [
    "/* Generated by scripts/generate_ui_font.py (Carlito, SIL OFL 1.1 -",
    " * see vendor/FONT-LICENSE.txt). 64 px master; ui_draw.c",
    " * area-average downsamples it to every request size. */",
    f"#define SANS_PT {SANS_PT}",
    f"#define SANS_RH {SANS_RH}",
    "static const struct { unsigned offset; unsigned short width, advance; } sans_glyphs[] = {",
]
lines += [f"{{{offset},{width},{advance}}}," for offset, width, advance in glyphs]
lines += ["};", "static const unsigned char sans_pixels[] = {"]
lines += [",".join(map(str, pixels[i:i + 128])) + ","
          for i in range(0, len(pixels), 128)]
lines += ["};", ""]
output.write_text("\n".join(lines), encoding="ascii", newline="\n")
print(f"baked {len(glyphs)} glyphs, {len(pixels)} coverage bytes -> {output}")
